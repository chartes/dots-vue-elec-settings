    <h2>La collection</h2>
    <p>Les <i>Actes royaux du Poitou</i> sont publiés en douze tomes couvrant les années 1302 à 1483. La version historique donnait accès à chaque tome depuis une page unique et proposait également une documentation et le téléchargement des sources.</p>
