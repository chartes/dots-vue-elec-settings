    <h2>Introduction</h2>
    <p>Du XIII<sup>e</sup> au XV<sup>e</sup> siècle, lorsqu’un auteur voulait faire un travail sérieux sur l’histoire de France, il allait se renseigner à Saint-Denis, abbaye proche du pouvoir capétien et gardienne des insignes royaux, qui se flattait d’être la mémoire de la dynastie.</p>
    <p>Les moines bénédictins y proposaient un recueil de textes historiques compilés à partir de sources antérieures et régulièrement tenus à jour. Avec ses erreurs, ses lacunes et ses réussites, ce recueil formait une base de travail pour les historiens et chroniqueurs.</p>
    <p>La présente édition donne accès au manuscrit Paris, BnF lat. 5925. Elle permet de suivre la composition des Chroniques, d’observer leurs sources et de comparer les transformations du texte au fil de sa tradition.</p>
    <p><i>Texte adapté de l’introduction de l’édition historique.</i></p>
