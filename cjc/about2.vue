    <h2>B. Introduction de l’édition en ligne</h2>

    <h3>1. L’édition de P.-N. Rapetti et son complément</h3>

    <p>
      Le but de la présente édition est de donner à lire l’intégralité du
      <i>Livre de jostice et de plet</i> d’après le ms. Paris, BnF, fr. 2844.
    </p>

    <p>
      Comme l’édition partielle de P.-N. Rapetti annonce tous les chapitres qui composent le LJP,
      la structure formelle de l’édition de 1850 a servi de base à la création de la version numérique.
    </p>

    <p>
      L’édition numérique reproduit fidèlement la partie éditée par P.-N. Rapetti,
      couplée aux sections inédites éditées par G. Pastore.
    </p>

    <p>
      Une partie des noms propres renvoie aux fiches prosopographiques :
