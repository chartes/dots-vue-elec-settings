<h1>Les archives de Montferrand</h1><p>Les Archives départementales du Puy-de-Dôme conservent une collection de documents administratifs relatifs à la ville de Montferrand qui est d'une richesse remarquable&nbsp;: nous y trouvons des chartes, des livres de comptes, des rôles de taille, les procès-verbaux des séances du consulat, de nombreuses pièces de correspondance - la plupart en langue vulgaire - qui s'échelonnent de la fin du XII<sup>e</sup> au milieu du XVIII<sup>e</sup> siècle, et qui offrent sur les événements politiques et administratifs, sur la vie urbaine et sur la langue en Auvergne, un témoignage exceptionnel. Pour juger de son ampleur, il suffit de consulter les deux volumes in-4<sup>o</sup> qu'Emmanuel Teilhard de Chardin a consacrés au « Fonds de Montferrand » dans l'<cite>Inventaire sommaire des archives communales antérieures à 1790</cite>. Peu de villes peuvent se vanter de posséder des archives qui remontent aussi loin dans le temps, et qui présentent une série aussi riche et aussi suivie de documents. </p><p>En raison de leur volume, il serait impossible de publier les archives consulaires de cette ville dans leur intégralité, même en se limitant à la partie médiévale. En revanche, mettre à la disposition du public les documents les plus anciens rédigés en occitan (XIII<sup>e</sup>-XIV<sup>e</sup>&nbsp;siècles) est à la fois possible et utile, tant pour les linguistes que pour les historiens. Nous avons édité, il y a une vingtaine d’années, le plus ancien des registres consulaires en langue d’oc (coté CC 154), qui couvre les années 1259-12721. Nous publions ici les livres de comptes qui font suite à ce premier registre, entre 1273 et 1319.</p><p>Les livres de comptes en bas-Auvergnat</p><p>Le tableau ci-dessous recense les principaux livres de comptes rédigés en bas-auvergnat qui sont conservés dans le fonds de Montferrand2. Ils sont disposés chronologiquement, en reprenant la numérotation d’E. Teilhard de Chardin.</p><table>
