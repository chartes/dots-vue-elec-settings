        <p class="texte">En la situant dans le cadre plus large d'une
vénération des anciens, la notion de « classique » peut être
                     opérationnelle pour le Moyen Âge si on la fonde
principalement sur une opposition d'ordre religieux entre
                     auteur ou texte païen et auteur ou texte chrétien, à
 l'exemple de la distinction faite par saint Jérôme dans
                     sa lettre à Julia Eustochium : </p>
        <blockquote style="font-style:italic;">
            <p class="texte">« Quae enim communicatio luci ad tenebras ?
 qui consensus Christo et Belial ? quid facit cum psalterio Horatius ?
cum evangeliis Maro ? cum apostolo Cicero ? […] simul bibere non debemus
 calicem Christi et
              calicem daemoniorum <sup><a id="appelnote2.1" class="appel_note" href="#footnote2.1">1</a></sup>
            </p>
        </blockquote>
        <p class="texte">On rappellera, en contrepoint de cette défiance affichée pour les auteurs païens, la place qu'occupe la
                     morale antique dans l'instruction médiévale. La possibilité qu'ils offraient d'une lecture chrétienne plus
                     que la perception de leur altérité a fondé le succès médiéval d'un certain nombre de philosophes de
                     l'Antiquité.</p>
        <p class="texte">Les auteurs de l'Antiquité gréco-romaine forment une partie bien individualisée au sein d'un corpus plus
                     vaste d'<em>auctoritates</em>. Dans le <em>Libellus totius operis apologeticus</em>, Vincent
                     de Beauvais hiérarchise les <em>auctoritates</em> sur trois niveaux. Les docteurs de l'église
                     occupent la plus haute place, suivis des autres docteurs, « <em>prudentes quidem et catholici</em> ». Viennent ensuite les auteurs païens :</p>
        <blockquote style="font-style:italic;">
            <p class="texte">« Tertium autem et infimum tenent gradum
philosophi doctoresque gentilium. Nam, etsi catholice fidei
                           veritatem ignoraverunt, mira tamen et
preclara quedam dixerunt de Creatore et creaturis, de virtutibus
                           quoque et viciis, que et fide catholica et
ratione humana manifeste probantur esse vera »<sup><a id="appelnote2.3" class="appel_note" href="#footnote2.3">3</a></sup>
            </p>
        </blockquote>
        <p class="texte">L'existence d'un corpus classique cohérent et bien établi dès le haut Moyen Âge est confirmé par le grand
                     nombre des florilèges classiques :</p>
        <ul>
            <li>Birger Munk Olsen, « Les classiques latins dans les florilèges médiévaux antérieurs au XIIIe siècle », dans <em>Revue d'histoire des textes</em>, t. 9, 1979, p. 47-121 et t. 10,
                        1980, p. 115-164. </li>
        </ul>
